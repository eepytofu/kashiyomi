// Records the dictionary release a build expects, so `npm run build` never
// touches the network and every build is reproducible.
//
//   npm run pin-dict
//
// Writes src/engine/dictionaryPins.ts, which is committed and reviewable: the
// point is that a change of dictionary version shows up in a diff rather than
// happening silently at build time.
//
// The pinned SHA-256 is what makes a mirror safe to download from. Fetching it
// at runtime instead would drop the check exactly where it matters most, since
// a user whose upstream is blocked cannot reach the metadata API to get the
// hash either.

import { writeFileSync } from "node:fs";
import path from "node:path";

const OUT = path.resolve(import.meta.dirname, "..", "src", "engine", "dictionaryPins.ts");
const PYPI = "https://pypi.org/pypi/SudachiDict-core/json";

/**
 * One request, one edition, a digest the publisher asserted.
 *
 * PyPI rather than GitHub Releases, which briefly served this while the plugin
 * also offered `full`: `full` has no PyPI wheel, so it needed a host that
 * carried all three. With one edition the publisher's own index is the shortest
 * path to the same digest, and it is the index the mirror mirrors.
 */
const response = await fetch(PYPI, { headers: { "user-agent": "kashiyomi-pin-dictionary" } });
if (!response.ok) throw new Error(`PyPI returned HTTP ${response.status}`);
const body = await response.json();
const version = body.info?.version;
if (typeof version !== "string") throw new Error("PyPI did not report a version");

const wheel = body.urls?.find((u) => u.packagetype === "bdist_wheel");
// An sdist is a ~9 KB stub that downloads the real archive at install time, so
// its digest vouches for nothing. Refusing here is the same rule the runtime
// parser applies.
if (!wheel) throw new Error(`no wheel published for ${version}; refusing to pin an sdist`);
const sha256 = wheel.digests?.sha256;
if (typeof sha256 !== "string" || !/^[0-9a-f]{64}$/.test(sha256)) {
  throw new Error(`PyPI published no usable sha256 for ${version}`);
}

const pin = { version, url: wheel.url, sha256, size: wheel.size };
console.log(`core  ${version}  ${(wheel.size / 1048576).toFixed(1)} MB  ${sha256.slice(0, 16)}...`);

const out = `// GENERATED by tools/pin-dictionary.mjs, run \`npm run pin-dict\` to refresh.
//
// The dictionary release this build expects, so building needs no network and a
// version change appears in a diff instead of happening silently.
//
// The digest is the publisher's own, from the PyPI JSON API. That is what lets a
// download come from a mirror and still be trusted: the bytes are checked
// against this, never against whoever served them.
//
// Pinned ${new Date().toISOString().slice(0, 10)}.

import type { DictionaryRelease } from "./dictionarySource.ts";

const PIN: DictionaryRelease = ${JSON.stringify(pin, null, 2).replace(/"(version|url|sha256|size)":/g, "$1:")};

/**
 * What shipped with this build. Used as the offline fallback when no metadata
 * source answers, and as the baseline a user can always install.
 *
 * Carries its URL. Without one the offline fallback knew the exact version,
 * size and hash it wanted and had nowhere to fetch it from, so every metadata
 * source failing meant no install was possible at all.
 */
export function pinnedRelease(): DictionaryRelease {
  return PIN;
}
`;

writeFileSync(OUT, out, "utf8");
console.log(`\nwrote ${path.relative(process.cwd(), OUT)}`);
