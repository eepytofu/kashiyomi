// Refreshes the reviewed Core and Full release metadata used by runtime installs.
// Building never touches the network; running this command is the explicit,
// reviewable point where publisher versions and digests enter the repository.

import { writeFileSync } from "node:fs";
import path from "node:path";

const OUT = path.resolve(import.meta.dirname, "..", "src", "engine", "dictionaryPins.ts");
const RELEASES = "https://api.github.com/repos/WorksApplications/SudachiDict/releases/latest";
const EDITIONS = ["core", "full"];

const response = await fetch(RELEASES, {
  headers: {
    accept: "application/vnd.github+json",
    "user-agent": "kashiyomi-pin-dictionary",
    ...(process.env.GITHUB_TOKEN ? { authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
  },
});
if (!response.ok) {
  const remaining = response.headers.get("x-ratelimit-remaining");
  const reset = Number(response.headers.get("x-ratelimit-reset") ?? 0) * 1000;
  const resetNote = reset > Date.now() ? `; resets in about ${Math.ceil((reset - Date.now()) / 60000)} min` : "";
  const tokenNote = remaining === "0" ? "; set GITHUB_TOKEN to use an authenticated quota" : "";
  throw new Error(`GitHub releases returned HTTP ${response.status}${resetNote}${tokenNote}`);
}

const release = await response.json();
const version = String(release.tag_name).replace(/^v/, "");
const pins = {};
for (const edition of EDITIONS) {
  const name = `sudachidict_${edition}-${version}-py3-none-any.whl`;
  const asset = release.assets?.find((candidate) => candidate.name === name);
  if (!asset) throw new Error(`${name} is not in release ${release.tag_name}`);
  const digest = String(asset.digest ?? "");
  if (!digest.startsWith("sha256:")) {
    throw new Error(`${name} has no publisher SHA-256 digest`);
  }
  pins[edition] = {
    version,
    // Core keeps PyPI as its preferred runtime route. Full has no self-contained
    // PyPI wheel, so the publisher's GitHub release is its direct source.
    url: asset.browser_download_url,
    sha256: digest.slice("sha256:".length),
    size: asset.size,
  };
  console.log(
    `${edition.padEnd(4)} ${version} ${(asset.size / 1048576).toFixed(1)} MB ${pins[edition].sha256}`,
  );
}

// PyPI gives Core a geographically independent official mirror path. Keep that
// preferred URL while retaining the same publisher digest learned above.
const coreResponse = await fetch(`https://pypi.org/pypi/SudachiDict-core/${version}/json`);
if (!coreResponse.ok) throw new Error(`PyPI Core returned HTTP ${coreResponse.status}`);
const coreBody = await coreResponse.json();
const coreWheel = coreBody.urls?.find((candidate) => candidate.packagetype === "bdist_wheel");
if (!coreWheel || coreWheel.digests?.sha256 !== pins.core.sha256) {
  throw new Error("Core PyPI wheel does not match the publisher release digest");
}
pins.core.url = coreWheel.url;
pins.core.size = coreWheel.size;

const body = `// GENERATED by tools/pin-dictionary.mjs, run \`npm run pin-dict\` to refresh.

import type { DictionaryEdition, DictionaryRelease } from "./dictionarySource.ts";

const PINS: Record<DictionaryEdition, Omit<DictionaryRelease, "edition">> = ${JSON.stringify(pins, null, 2)
  .replace(/"(version|url|sha256|size)":/g, "$1:")
  .replace(/"(core|full)":/g, "$1:")};

/** The reviewed release this build can always install without metadata lookup. */
export function pinnedRelease(edition: DictionaryEdition = "core"): DictionaryRelease {
  return { edition, ...PINS[edition] };
}
`;

writeFileSync(OUT, body, "utf8");
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
