export function tDictionaryPhase(phase: OperationPhase): string {
  return t(PHASE_KEYS[phase]);
}

export function tDictionaryOperation(kind: OperationKind, edition?: string): string {
  return tf(OPERATION_KEYS[kind], { edition: edition ?? "" });
}

export function tDictionaryError(error: DictionaryErrorCode | "cancelUnavailable"): string {
  return t(ERROR_KEYS[error]);
}
